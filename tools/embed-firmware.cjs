// Copies firmware/sensor_reader.ino.hex into js/firmware-hex.js so the page can install it.
// (A web page opened straight from disk is not allowed to read other files, so the
// firmware has to live inside a script.) Run after recompiling the sketch:
//   node tools/embed-firmware.cjs
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const hex = fs.readFileSync(path.join(root, 'firmware', 'sensor_reader.ino.hex'), 'utf8').trim();
const out = `// Generated by tools/embed-firmware.cjs from firmware/sensor_reader.ino.hex. Do not edit by hand.
window.STRIP_FIRMWARE_HEX = ${JSON.stringify(hex + '\n')};
`;
fs.writeFileSync(path.join(root, 'js', 'firmware-hex.js'), out);
console.log(`Wrote js/firmware-hex.js (${hex.split('\n').length} lines of HEX).`);
